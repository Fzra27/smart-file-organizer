function t(key, values = {}) {
    const singular = {
        '{count} dosya': '{count} Datei',
        '{count} kopya grubu': '{count} Duplikatgruppe',
        '{date} · {count} kayıt': '{date} · {count} Eintrag',
        '{count} dosya taşındı.': '{count} Datei verschoben.',
        '{count} dosya geri alındı.': '{count} Datei zurückverschoben.',
        ' · {count} dosya düzenlendi': ' · {count} Datei geordnet'
    };
    const template = language === 'de'
        ? (Number(values.count) === 1 && singular[key] ? singular[key] : (german[key] ?? key))
        : key;
    return template.replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
function translateStatic() {
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach(node => {node.textContent = t(node.dataset.i18n);});
    for (const attr of ['placeholder', 'aria-label']) {
        document.querySelectorAll('[data-i18n-' + attr + ']').forEach(node => {
            node.setAttribute(attr, t(node.getAttribute('data-i18n-' + attr)));
        });
    }
}
function translatedError(message) {
    return String(message).split('\n').map(line => {
        if (language !== 'de') return line;
        if (german[line]) return german[line];
        for (const key of Object.keys(german)) {
            if (key.endsWith(': ') && line.startsWith(key)) return german[key] + line.slice(key.length);
        }
        return line; // OS diagnostics and file paths are preserved verbatim.
    }).join('\n');
}
function autoStatus(message) {
    const match = message.match(/^(.*) · (\d+) dosya düzenlendi(.*)$/);
    return match ? match[1] + t(' · {count} dosya düzenlendi', {count: match[2]}) + translatedError(match[3]) : translatedError(message);
}
